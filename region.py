# ─────────────────────────────────────────────────────────────────────────
#  ФОРА — fora.ua
#  Каждый магазин = filialId. Найдены через GetPickupFilials с businessId=4.
#  Внимание: у Фори «вул. Маркса Карла, 22» в Іллінцях — это и есть
#  вул. Європейська, 22 (улицу переименовали, у Фори старое название).
# ─────────────────────────────────────────────────────────────────────────
FORA_BUSINESS_ID = 4
