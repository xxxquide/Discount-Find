"""
region.py — привязка к региону Вінниця / Іллінці.

Здесь в одном месте собраны идентификаторы конкретных магазинов,
чтобы бот показывал цены и наличие ИМЕННО твоих супермаркетов,
а не средние по Украине.

Все идентификаторы найдены и проверены живыми запросами 24.07.2026.
Если переедешь или захочешь другой магазин — меняй только этот файл.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class StoreLocation:
    """Один физический магазин сети."""
    store_key: str      # ключ парсера: silpo / atb / fora / grosh
    city: str           # «Вінниця» или «Іллінці»
    address: str        # человекочитаемый адрес
    location_id: str    # идентификатор магазина в системе сети


# ─────────────────────────────────────────────────────────────────────────
#  АТБ — atbmarket.com
#  Каталог привязывается к магазину через cookie nstore_id.
#  Город Вінниця = 583, список магазинов: POST /site/getstore {city: 583}
# ─────────────────────────────────────────────────────────────────────────
