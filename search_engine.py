"""
search_engine.py — «умный» поиск простыми словами.

Задача: чтобы «макарони» находило «Макаронні вироби», «сир» — не приносило
«сирники», а «кола» — находило «Напій Coca-Cola». Магазинные поисковики
это делают плохо, поэтому мы:

  1) РАСШИРЯЕМ запрос синонимами: «макарони» → макарони, спагеті, паста…
     (словарь SYNONYMS ниже — обычные украинские слова);
  2) НОРМАЛИЗУЕМ буквы: і/и, ї/и, є/е, ґ/г, апострофы — чтобы «чіпси»
     находило «чипси» (магазины пишут по-разному);
  3) СЧИТАЕМ РЕЛЕВАНТНОСТЬ каждого товара по названию: точное вхождение,
     совпадение начала слова, похожесть с опечатками (difflib);
  4) ОТСЕКАЕМ мусор: если ищем «сир», не показываем «сирники» и «сирок»
     (стоп-слова STOP_FORMS), но «Сир твердий» — покажем.

Всё работает локально, без запросов к сайтам, поэтому быстро.
"""
from __future__ import annotations

import re
import unicodedata
from difflib import SequenceMatcher

# ── 1. Нормализация букв ─────────────────────────────────────────────────

_LETTER_MAP = {
    "і": "и", "ї": "и", "й": "и", "ы": "и",
    "є": "е", "э": "е", "ё": "е",
    "ґ": "г",
    "'": "", "’": "", "ʼ": "", "`": "",
}


def normalize(text: str) -> str:
    """'Чіпси' и 'чипси' → 'чипси'. Убирает регистр, апострофы, разнобой букв."""
    text = unicodedata.normalize("NFC", text or "").lower()
    return "".join(_LETTER_MAP.get(ch, ch) for ch in text)


def tokens(text: str) -> list[str]:
    """Разбивает строку на значимые слова (от 2 букв)."""
    return [w for w in re.split(r"[^\wа-яёіїєґ]+", normalize(text)) if len(w) >= 2]


def stem(word: str) -> str:
    """
    Грубая «основа» слова: отбрасываем típичные украинские окончания.
    «макарони» → «макарон», «сиру» → «сир», «яйця» → «яйц».
    """
    word = normalize(word)
    for suffix in ("ами", "ями", "ові", "ева", "ово", "ий", "ій", "ая", "ої", "ої",
                   "и", "і", "а", "я", "у", "ю", "е", "о", "ь"):
        if len(word) - len(suffix) >= 3 and word.endswith(suffix):
            return word[: -len(suffix)]
    return word


