# Слова, которые НЕ должны считаться совпадением, хотя начинаются так же.
# Например, ищем «сир» — «сирники» и «сирок» это другое блюдо.
STOP_FORMS: dict[str, list[str]] = {
    "сир": ["сирник", "сироп", "сировин", "сирень"],
    "молоко": ["молокочай"],
    "масло": ["маслина", "масляна кислота"],
    "кава": ["кавун", "кавьяр"],
    "сік": ["сікатор"],
}


def expand_query(query: str) -> list[str]:
    """
    Расширяет пользовательский запрос синонимами.
    «макарони» → ['макарони', 'макаронні вироби', 'спагеті', 'паста', …]
    Если слова нет в словаре — возвращаем как есть (одним вариантом).
    """
    q = normalize(query).strip()
    if not q:
        return []

    # прямое попадание
    if q in SYNONYMS:
        return SYNONYMS[q]

    # попадание по основе слова («макаронів» → «макарони»)
    q_stem = stem(q)
    for key, values in SYNONYMS.items():
        if stem(key) == q_stem:
            return values

    # запрос из нескольких слов: расширяем каждое известное слово
    words = tokens(q)
    if len(words) > 1:
        expanded: list[str] = [query]
        for w in words:
            if w in SYNONYMS:
                expanded.extend(SYNONYMS[w][:3])
        return list(dict.fromkeys(expanded))

    return [query]


# ── 3. Оценка релевантности ──────────────────────────────────────────────

# Слова-«дисквалификаторы»: если синоним двусмысленный, а рядом в названии
# стоит одно из этих слов — значит, это товар из другой категории.
# Пример: «паста» = макароны, но «Паста зубна» — это гигиена.
AMBIGUOUS_GUARDS: dict[str, list[str]] = {
    "паста": ["зубна", "зубную", "томатна", "арахісова", "шоколадна", "для взуття",
              "очищуюча", "очищувальна", "чистяча", "для рук", "полірувальна"],
    "масло": ["моторне", "машинне", "для догляду", "ефірна", "ефірне"],
    "кола": ["коляска", "колаген"],
    "рис": ["рисовий папір", "для обличчя"],
    "сік": ["для волосся"],
    "мило": ["мильниця"],
}


def _is_wrong_category(synonym: str, title_words: list[str]) -> bool:
    """True, если синоним в этом названии означает не то, что мы ищем."""
    guards = AMBIGUOUS_GUARDS.get(normalize(synonym))
    if not guards:
        return False
    joined = " ".join(title_words)
    return any(normalize(g) in joined for g in guards)


def relevance(query: str, title: str) -> float:
    """
    Насколько товар «title» подходит запросу «query».
    Возвращает 0.0 (не подходит) … 1.0 (идеально).

    Логика по убыванию веса:
      1.00 — название начинается с запроса («Сир твердий» для «сир»)
      0.90 — запрос встречается как отдельное слово
      0.75 — совпал синоним
      0.60 — совпала основа слова («макарон» в «макаронні»)
      0.45 — похоже с опечаткой (≥ 80 % сходства)
    """
    q_norm = normalize(query).strip()
    t_norm = normalize(title)
    if not q_norm or not t_norm:
        return 0.0

    # стоп-формы: «сирники» не подходят под «сир»
    for stop in STOP_FORMS.get(q_norm, []):
        if normalize(stop) in t_norm:
            return 0.0

    t_words = tokens(t_norm)

    # 1) прямое начало названия
    if t_norm.startswith(q_norm):
        return 1.0

    # 2) отдельное слово в названии
    if q_norm in t_words:
        return 0.9

    # 3) синонимы — но только как ОТДЕЛЬНОЕ слово (или начало слова),
    #    иначе «паста» из синонимов макарон находит «Паста зубна»
    for syn in expand_query(query):
        syn_n = normalize(syn).strip()
        if not syn_n:
            continue
        if " " in syn_n:                      # многословный синоним
            if syn_n in t_norm:
                return 0.75
            continue
        for w in t_words:                     # однословный — сверяем по словам
            if w == syn_n or stem(w) == stem(syn_n):
                # «паста» подходит, если рядом нет слов из чужой категории
                if not _is_wrong_category(syn_n, t_words):
                    return 0.75

    # 4) совпадение основы
    q_stem = stem(q_norm)
    if len(q_stem) >= 3:
        for w in t_words:
            if w.startswith(q_stem) or stem(w) == q_stem:
                return 0.6

    # 5) опечатки — сравниваем с каждым словом названия
    best = 0.0
    for w in t_words:
        if abs(len(w) - len(q_norm)) <= 3:
            ratio = SequenceMatcher(None, q_norm, w).ratio()
            best = max(best, ratio)
    if best >= 0.8:
        return 0.45

    return 0.0


def rank_products(query: str, products: list, min_score: float = 0.4) -> list:
    """
    Оставляет подходящие товары и сортирует по релевантности,
    а при равной релевантности — по размеру скидки.

    products — список объектов Product (у них есть .title и .discount_pct).
    """
    scored = []
    for p in products:
        score = relevance(query, p.title)
        if score >= min_score:
            scored.append((score, p))

    scored.sort(key=lambda pair: (pair[0], pair[1].discount_pct), reverse=True)
    return [p for _score, p in scored]


def search_index(query: str, products: list, limit: int = 50) -> list:
    """
    Поиск по локальному «индексу» — уже скачанному каталогу акций.

    Сначала строгий отбор по релевантности. Если совсем ничего не нашлось,
    делаем мягкую попытку по основе слова — но с той же защитой от
    чужих категорий, чтобы «макарони» не приносили зубную пасту.
    """
    result = rank_products(query, products, min_score=0.4)
    if result:
        return result[:limit]

    # мягкий запасной поиск: основа запроса как начало любого слова названия
    q_stems = [stem(w) for w in tokens(query) if len(stem(w)) >= 4]
    if not q_stems:
        return []

    fallback = []
    for p in products:
        t_words = tokens(p.title)
        if any(w.startswith(s) for s in q_stems for w in t_words):
            if not any(_is_wrong_category(s, t_words) for s in q_stems):
                fallback.append(p)
    fallback.sort(key=lambda p: p.discount_pct, reverse=True)
    return fallback[:limit]
